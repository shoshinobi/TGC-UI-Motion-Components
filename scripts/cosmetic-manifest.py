#!/usr/bin/env python3
"""Regenerate src/components/cosmeticItems.ts from src/assets/cosmeticThumbs/*.png.

Each thumbnail has a different amount of empty (transparent) space around the item,
so the carousel fits the item's *visible* box, not the whole image. This measures
that box once (alpha > 8) and writes it as fractions of the image size.

    python3 scripts/cosmetic-manifest.py
"""
import json, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, 'src', 'assets', 'cosmeticThumbs')
OUT = os.path.join(ROOT, 'src', 'components', 'cosmeticItems.ts')

items = []
for f in sorted(os.listdir(DIR), key=str.lower):
    if not f.lower().endswith('.png'):
        continue
    im = Image.open(os.path.join(DIR, f)).convert('RGBA')
    a = im.getchannel('A').point(lambda v: 255 if v > 8 else 0)
    bb = a.getbbox() or (0, 0, im.width, im.height)
    w, h = im.size
    items.append({
        'name': os.path.splitext(f)[0],
        'file': f,
        'w': w, 'h': h,
        # visible box, as fractions of the image: x0, y0, x1, y1
        'box': [round(bb[0] / w, 4), round(bb[1] / h, 4), round(bb[2] / w, 4), round(bb[3] / h, 4)],
    })

lines = [
    '// GENERATED by scripts/cosmetic-manifest.py — do not edit by hand; re-run it after adding thumbnails.',
    '// `box` = the item\'s visible (non-transparent) area as fractions of the image (x0, y0, x1, y1),',
    '// so every item can be fitted to the same card space whatever padding its PNG has.',
    '',
    "const urls = import.meta.glob('@/assets/cosmeticThumbs/*.png', { eager: true, query: '?url', import: 'default' }) as Record<string, string>",
    '',
    'export type CosmeticItem = { name: string; url: string; w: number; h: number; box: [number, number, number, number] }',
    '',
    'const RAW: (Omit<CosmeticItem, \'url\'> & { file: string })[] = [',
]
for it in items:
    lines.append('  ' + json.dumps({'name': it['name'], 'file': it['file'], 'w': it['w'], 'h': it['h'], 'box': it['box']}, ensure_ascii=False) + ',')
lines += [
    ']',
    '',
    'const urlFor = (file: string) => {',
    "  const key = Object.keys(urls).find((k) => k.endsWith('/' + file))",
    "  return key ? urls[key] : ''",
    '}',
    '',
    '/** every cosmetic thumbnail, A–Z */',
    'export const COSMETIC_ITEMS: CosmeticItem[] = RAW.map(({ file, ...it }) => ({',
    '  ...it,',
    '  url: urlFor(file),',
    '}))',
    '',
    'export const COSMETIC_NAMES = COSMETIC_ITEMS.map((i) => i.name)',
    '',
]
open(OUT, 'w').write('\n'.join(lines))
print(f'wrote {len(items)} items → {os.path.relpath(OUT, ROOT)}')
